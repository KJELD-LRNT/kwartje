//! PDF rendering. The real renderer runs the Typst CLI on
//! `templates/invoice.typ` with a JSON data file; tests use a fake.

use std::path::PathBuf;
use std::process::Command;
use std::time::Duration;

use anyhow::{bail, Context, Result};

pub const INVOICE_TEMPLATE: &str = include_str!("../templates/invoice.typ");

/// Renders a Typst template with `data.json` and extra files (e.g. the logo).
pub trait PdfRenderer: Send + Sync {
    fn render(
        &self,
        template: &str,
        data_json: &str,
        assets: &[(String, Vec<u8>)],
    ) -> Result<Vec<u8>>;
}

/// Render on a blocking thread, so Typst never stalls the async workers.
pub async fn render_blocking(
    renderer: std::sync::Arc<dyn PdfRenderer>,
    template: &'static str,
    data_json: String,
    assets: Vec<(String, Vec<u8>)>,
) -> Result<Vec<u8>> {
    tokio::task::spawn_blocking(move || renderer.render(template, &data_json, &assets))
        .await
        .map_err(|e| anyhow::anyhow!("PDF-taak afgebroken: {e}"))?
}

pub struct TypstCli {
    pub binary: PathBuf,
    pub timeout: Duration,
}

impl PdfRenderer for TypstCli {
    fn render(
        &self,
        template: &str,
        data_json: &str,
        assets: &[(String, Vec<u8>)],
    ) -> Result<Vec<u8>> {
        let dir = tempfile::tempdir().context("tijdelijke map voor PDF")?;
        std::fs::write(dir.path().join("main.typ"), template)?;
        std::fs::write(dir.path().join("data.json"), data_json)?;
        for (name, bytes) in assets {
            // asset names are generated by us (e.g. "logo.png"), never user input
            if name.contains('/') || name.contains("..") {
                bail!("ongeldige bestandsnaam voor PDF-bijlage");
            }
            std::fs::write(dir.path().join(name), bytes)?;
        }
        let out = dir.path().join("out.pdf");
        // stderr to a file, not a pipe: a full pipe (lots of warnings) would
        // stall Typst until the timeout.
        let err_path = dir.path().join("stderr.txt");
        let err_file = std::fs::File::create(&err_path)?;
        let mut child = Command::new(&self.binary)
            .arg("compile")
            .arg("--root")
            .arg(dir.path())
            .arg(dir.path().join("main.typ"))
            .arg(&out)
            .stdout(std::process::Stdio::null())
            .stderr(err_file)
            .spawn()
            .with_context(|| {
                format!(
                    "Typst starten ({}) mislukt; is Typst geïnstalleerd?",
                    self.binary.display()
                )
            })?;
        let start = std::time::Instant::now();
        loop {
            if let Some(status) = child.try_wait()? {
                if !status.success() {
                    let err = std::fs::read_to_string(&err_path).unwrap_or_default();
                    let err: String = err.trim().chars().take(2000).collect();
                    bail!("Typst gaf een fout: {err}");
                }
                break;
            }
            if start.elapsed() > self.timeout {
                let _ = child.kill();
                bail!("Typst duurde te lang");
            }
            std::thread::sleep(Duration::from_millis(20));
        }
        let pdf = std::fs::read(&out).context("PDF lezen")?;
        if !pdf.starts_with(b"%PDF") {
            bail!("Typst leverde geen PDF");
        }
        Ok(pdf)
    }
}

/// Test renderer: returns a tiny fake PDF containing the data.
pub struct FakePdf {
    pub fail: bool,
}

impl PdfRenderer for FakePdf {
    fn render(
        &self,
        _template: &str,
        data_json: &str,
        _assets: &[(String, Vec<u8>)],
    ) -> Result<Vec<u8>> {
        if self.fail {
            bail!("PDF maken mislukt (test)");
        }
        let mut v = b"%PDF-1.4 fake\n".to_vec();
        v.extend_from_slice(data_json.as_bytes());
        Ok(v)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn typst_errors_are_reported() {
        if Command::new("typst").arg("--version").output().is_err() {
            eprintln!("typst not installed; skipping");
            return;
        }
        let t = TypstCli {
            binary: "typst".into(),
            timeout: Duration::from_secs(30),
        };
        let e = t.render("#let x = ", "{}", &[]).unwrap_err().to_string();
        assert!(e.starts_with("Typst gaf een fout: "), "{e}");
        assert!(e.len() > "Typst gaf een fout: ".len(), "{e}");
    }
}
